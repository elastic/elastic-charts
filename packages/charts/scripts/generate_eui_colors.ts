/**
 * Generates `src/utils/themes/eui_borealis_colors.generated.ts` from `@elastic/eui-theme-borealis`.
 *
 * Usage: yarn generate:eui-colors (from packages/charts)
 */

import fs from 'fs';
import path from 'path';

import prettier from 'prettier';

import { extractEuiColors } from './extract_eui_colors';

const OUTPUT_PATH = path.resolve(__dirname, '../src/utils/themes/eui_borealis_colors.generated.ts');

function getEuiThemeBorealisVersion(): string {
  // `package.json` is not in the package's `exports`, so resolve it relative to the CJS entry (`lib/cjs/index.js`).
  const packageJsonPath = path.resolve(require.resolve('@elastic/eui-theme-borealis'), '../../../package.json');
  return JSON.parse(fs.readFileSync(packageJsonPath, 'utf8')).version;
}

function toSource(constants: Record<string, unknown>, version: string): string {
  const header = `/*
 * Copyright Elasticsearch B.V. and/or licensed to Elasticsearch B.V. under one
 * or more contributor license agreements. Licensed under the Elastic License
 * 2.0 and the Server Side Public License, v 1; you may not use this file except
 * in compliance with, at your election, the Elastic License 2.0 or the Server
 * Side Public License, v 1.
 */

// This file is generated by packages/charts/scripts/generate_eui_colors.ts from
// @elastic/eui-theme-borealis@${version}. Do not edit it manually.
`;
  const body = Object.entries(constants)
    .map(([name, value]) => `/** @internal */\nexport const ${name} = ${JSON.stringify(value)} as const;`)
    .join('\n\n');
  return `${header}\n${body}\n`;
}

async function main() {
  const config = await prettier.resolveConfig(OUTPUT_PATH);
  const source = toSource(extractEuiColors(), getEuiThemeBorealisVersion());
  const formatted = await prettier.format(source, { ...config, filepath: OUTPUT_PATH });
  fs.writeFileSync(OUTPUT_PATH, formatted);
  // eslint-disable-next-line no-console
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_PATH)}`);
}

main().catch((error) => {
  // eslint-disable-next-line no-console
  console.error(error);
  process.exitCode = 1;
});
