#!/usr/bin/env bash

# pnpm refuses to reuse node_modules linked from another store path (ERR_PNPM_UNEXPECTED_STORE).
# The host sees the checkout at its own path and the docker steps at /app, so whichever side
# installs next has to remove the node_modules linked by the other one.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/../.."

modules_yaml=node_modules/.modules.yaml
[[ -f "$modules_yaml" ]] || exit 0

expected_store="$(pnpm store path)"
linked_store="$(sed -n 's/^ *"storeDir": "\(.*\)",\{0,1\}$/\1/p' "$modules_yaml")"

if [[ "$linked_store" != "$expected_store" ]]; then
  echo " -- removing node_modules linked from $linked_store, the store is now $expected_store"
  rm -rf node_modules packages/*/node_modules storybook/node_modules docs/node_modules e2e/node_modules .buildkite/node_modules
fi
